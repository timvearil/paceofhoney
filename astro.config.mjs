// @ts-check
import { defineConfig } from 'astro/config';
import sitemap from '@astrojs/sitemap';
import { unified } from '@astrojs/markdown-remark';
import { remarkObsidian } from './src/plugins/remark-obsidian.mjs';
import { rehypeFigures } from './src/plugins/rehype-figures.mjs';
import { remarkDialogue } from './src/plugins/remark-dialogue.mjs';
import { remarkTypography } from './src/plugins/remark-typography.mjs';
import images from './src/integrations/images.mjs';

// Канонический домен. Без него неверно соберутся sitemap и абсолютные og:image.
const SITE = 'https://paceofhoney.me';

export default defineConfig({
  site: SITE,

  // Статическая генерация: на выходе только готовый HTML, сервер не нужен.
  output: 'static',

  // Локальный сервер разработки. Касается только команды npm run dev,
  // на опубликованный сайт не влияет никак.
  server: {
    // Явно привязываемся к IPv4-адресу. Без этой строки Node 17+ на Windows
    // поднимает сервер только на IPv6 ([::1]), тогда как браузер по адресу
    // localhost идёт на IPv4 (127.0.0.1) — и получает ERR_CONNECTION_REFUSED.
    host: '127.0.0.1',
    port: 4321,
  },

  integrations: [
    // Следит за архивом иллюстраций, пока идёт работа: новый кадр появляется
    // на странице сам, без перезапуска сервера.
    images(),
    sitemap({
      /*
       * В карте сайта — только канонические адреса.
       *
       * Отсюда три исключения, и каждое стоило бы дубликатов в выдаче:
       *
       *   · служебные фрагменты `/partial` — голые куски глав без оболочки,
       *     которые подгружает читалка. Для поисковика это копия статьи;
       *   · боковые нити `/series/{id}/{slug}` — та же глава, читаемая другой
       *     серией. Её `canonical` указывает на короткий адрес, и класть её
       *     в карту значит спорить с самим собой: «вот страница, но настоящая
       *     она другая»;
       *   · сквозная нить `/all/{slug}` — тот же текст, читаемый подряд
       *     по всему сайту. Канонический адрес у него прежний, и в карте
       *     ему делать нечего ровно по той же причине, что и боковой нити;
       *   · всё, что начинается с подчёркивания, — служебное по соглашению.
       */
      filter: (page) => {
        const path = new URL(page).pathname;
        if (path.includes('/partial')) return false;
        if (/^\/series\/[^/]+\/[^/]+/.test(path)) return false;
        if (/^\/all\//.test(path)) return false;
        return !path.includes('/_');
      },
    }),
  ],

  image: {
    // Адаптивные изображения по умолчанию: Astro сам режет несколько размеров
    // и проставляет srcset с sizes. Для проекта, где фотография — главный
    // носитель смысла, это принципиально: макроснимок мёда на 4 МБ не должен
    // уезжать целиком на телефон.
    layout: 'constrained',
    objectFit: 'cover',
    objectPosition: 'center',
  },

  markdown: {
    // Обработчик Markdown выбирается явно.
    //
    // По умолчанию в Astro 7 стоит новый быстрый Sätteri, но наш переводчик
    // синтаксиса Obsidian ([[ссылки]] и ![[вложения]]) написан под remark.
    // Поэтому переключаемся на unified — осознанный размен: теряем скорость
    // нового обработчика, получаем зрелую экосистему. Сборка сайта на два
    // десятка страниц занимает полторы секунды, экономить тут нечего.
    /*
      Умные кавычки обработчика выключены — их ставит наш плагин.

      `smartypants` — английская типографика: прямые кавычки он превращает
      в “лапки”, а нам нужны «ёлочки». И работает он раньше нашего плагина,
      так что тот не находил уже ни одной прямой кавычки и молчал. Найдено
      28.09 на первой архивной статье: по всему сайту стояли лапки, а
      проверка искала «нет прямых кавычек» — и радовалась, вместо того
      чтобы искать «есть ёлочки».
    */
    processor: unified({
      // Здесь же, а не в `markdown.smartypants`: в поле верхнего уровня
      // настройка объявлена устаревшей и в следующей большой версии исчезнет,
      // а вместе с ней вернулись бы английские лапки.
      smartypants: false,
      remarkPlugins: [[remarkObsidian, { root: process.cwd() }], remarkDialogue, remarkTypography],
      // Иллюстрации внутри текста доводятся до вида ведущего кадра: подпись,
      // проявление цвета, размер под ширину колонки. Именно rehype, а не
      // remark: к этому моменту Astro уже посчитал srcset, и мы ничего
      // не ломаем в его оптимизации.
      rehypePlugins: [rehypeFigures],
    }),
    // Подсветку кода настроим, когда появятся технические статьи.
    shikiConfig: { theme: 'github-dark', wrap: true },
  },

  build: {
    // Адреса без завершающего слэша: /posts/nektar-8, а не /posts/nektar-8/
    format: 'file',

    /*
      Стили едут внутри страницы, а не отдельным файлом.

      PageSpeed 28.09 показал ровно один запрос, блокирующий отрисовку, —
      наш общий CSS: 5,4 КБ по сети, но 150 мс ожидания, и всё это время
      браузер не рисует ни строчки. На медленной мобильной связи Lighthouse
      оценил задержку в полторы секунды, то есть почти во всю нашу LCP.

      Цена: +5 КБ сжатого текста в каждую страницу и потеря общего кеша
      между страницами. Для этого сайта цена почти нулевая: читатель идёт
      непрерывной лентой и остаётся на одной странице, докачивая только
      фрагменты статей, — а в них стилей нет.
    */
    inlineStylesheets: 'always',
  },
});
