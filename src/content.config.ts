/**
 * Описание коллекций контента.
 *
 * Здесь задано, из каких полей состоит глава, серия, статическая страница и
 * файлы настроек. Astro проверяет каждый файл по этой схеме на сборке и
 * **роняет сборку** при несоответствии: опечатка в `series_id`, забытая
 * `description`, кириллица в `slug`.
 *
 * Это не бюрократия, а страховка конвейера. Ошибка ловится за двадцать секунд
 * в GitHub Actions, а не обнаруживается через неделю битой карточкой на сайте.
 *
 * Спецификация: 01_Spec/tz-paceofhoney-v2.md, разделы 1.3, 4.1, 4.4
 */

import { defineCollection, z } from 'astro:content';
import { glob } from 'astro/loaders';
import { typography } from './plugins/remark-typography.mjs';

/* ---------------------------------------------------------------------------
   Типографика в полях, а не только в тексте

   Автор набирает одинаково везде: дефис вместо тире, прямые кавычки вместо
   ёлочек — так он писал тридцать лет, и переучиваться ради разметки незачем.
   Тело статьи приводит в порядок `remark-typography`, но поля фронтматтера
   до сих пор уезжали на сайт как написаны, и это было видно: в описаниях
   журналов, в подписях к кадрам, в строке «кому» на странице журнала.

   `typographic()` — тот же `z.string()`, только с правилом на выходе.
   Правила берутся из общей функции: разойтись с телом статьи им негде.

   Где не применяем: `id`, `slug`, `permalink`, пути к картинкам, адреса.
   Там дефис — часть значения, а не знак препинания, и «исправление» сломало
   бы ссылку.
   --------------------------------------------------------------------------- */

/**
 * Строка, прошедшая типографику при загрузке контента.
 *
 * Длину проверяем до преобразования: `transform` возвращает уже не строку
 * схемы, и `.min()` после него не существует. Поэтому минимум задаётся
 * параметром, а не цепочкой.
 *
 * ПОЧЕМУ СТРЕЛКА, А НЕ ПРОСТО `.transform(typography)`.
 *
 * Zod передаёт в преобразование два аргумента: значение и свой внутренний
 * объект для сообщений об ошибках. У `typography` второй параметр — это
 * состояние разбора кавычек, и чужой объект вставал на его место: счётчик
 * вложенности оказывался `undefined`, выбор кавычки по нему давал `NaN`,
 * а кавычка из списка по индексу `NaN` — пустоту.
 *
 * На сайте это выглядело так: `Подписка undefinedЗавтраundefined`
 * в заголовках и описаниях, при том что в теле статьи кавычки стояли верно.
 * Найдено 01.10 на локальном стенде. Сама функция была исправна — ошибка
 * жила ровно в этой строке, в способе её вызвать.
 *
 * Отсюда правило: функцию с необязательным вторым параметром никогда
 * не передавать обработчиком напрямую — ни в `transform`, ни в `map`,
 * ни в `then`. Только через стрелку, которая берёт ровно то, что нужно.
 */
const typographic = (min = 0) =>
  z
    .string()
    .min(min)
    .transform((v) => typography(v));

/** Латинский слаг: строчные буквы, цифры, дефис-разделитель. */
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

const slugField = z
  .string()
  .regex(
    SLUG,
    'Слаг пишется латиницей в нижнем регистре, слова через дефис: "nektar-8". ' +
      'Кириллица в адресе превращается в нечитаемую мешанину процентов ' +
      'и ломается при вставке в мессенджеры.',
  );

/* ---------------------------------------------------------------------------
   Главы сериалов и одиночные материалы
   ------------------------------------------------------------------------ */

const posts = defineCollection({
  loader: glob({ base: './src/content/posts', pattern: '**/*.md' }),
  schema: ({ image }) =>
    z
      .object({
        title: typographic(1),
        slug: slugField,
        description: z
          .string()
          .min(1, 'Без описания превью ссылки в Telegram и MAX приходит пустым.'),

        // Серии, в которые входит статья. Одна статья может принадлежать
        // нескольким сразу: глава «НектарАкций» одновременно может быть
        // главой «Ироничной пасеки».
        //
        // Порядок значим: ПЕРВАЯ серия — ведущая. Она попадает в плашку
        // «Глава N из M» и задаёт бесшовный поток чтения. Остальные выводятся
        // ссылками под текстом.
        //
        // Номера глав здесь НЕТ намеренно. Он вычисляется на сборке — по дате,
        // отдельно внутри каждой серии. С шестью сериями и перекрёстным
        // членством ручная нумерация превратилась бы в мучение: вставил одну
        // старую статью — перенумеровывай десятки файлов в трёх сериях.
        //
        // Пустой список — одиночный материал, рендерится классическим
        // шаблоном (ТЗ 3.3.2).
        series: z.array(z.string()).default([]),

        lead_image: image().optional(),
        lead_caption: typographic().optional(),
        lead_alt: typographic().optional(),

        /*
         * ЧЕЙ КАДР. Заполняется только в исключениях.
         *
         * По умолчанию (поля нет) фотография считается нашей: так заявлено
         * в подвале и на главной, и так оно и есть почти всегда. Разметка
         * проставляет автором проект, права — проекту, лицензию — из настроек.
         *
         * Заполнять, когда это не так:
         *   `ai`    — в кадре дорисованы детали моделью. Разметка говорит
         *             об этом прямо, вместо того чтобы выдавать машинную
         *             работу за съёмку;
         *   «Имя»   — снимал кто-то другой. Имя уходит в автора кадра,
         *             права при этом остаются при нём, а не при проекте.
         *
         * Зачем вообще: метаданные камеры до сайта не доезжают (их срезает
         * пересжатие, и это правильно — в них геометки). Поэтому честность
         * о происхождении кадра живёт здесь, в тексте, который мы пишем сами
         * и за который отвечаем доменом. Подделать EXIF — два клика;
         * подделать биографию домена с тринадцатью внешними профилями — нет.
         */
        lead_credit: z.string().optional(),

        // Дата публикации на сайте. По ней статья встаёт в ленту «свежее».
        date: z.coerce.date(),
        updated: z.coerce.date().optional(),

        // Уточнение порядка, когда две статьи одной серии стоят на одну дату.
        // Нужно редко: обычно дата публикации и есть сюжетный порядок.
        // Но при переносе сразу многих готовых текстов даты легко совпадают,
        // и тогда порядок глав решался бы алфавитом слага — то есть случайно.
        // Сборка такой случай не пропускает: требует расставить order явно.
        order: z.number().int().optional(),

        /*
         * ОТКУДА ПРИШЁЛ ТЕКСТ.
         *
         * Блок для архивных статей — тех, что были опубликованы десять-пятнадцать
         * лет назад на других площадках, зачастую уже заброшенных. Либо его нет
         * вовсе (обычная свежая статья), либо он заполнен целиком.
         *
         * Зачем это нужно, кроме честности перед читателем. Тексты, написанные
         * до появления генеративных моделей, — редкость, и отличить их от
         * сгенерированных нельзя никаким анализом стиля. Доказательством служит
         * независимый датированный снимок: страница, сохранённая веб-архивом
         * в 2013 году, не может быть написана моделью 2026-го. Поэтому поле
         * `archive` важнее, чем `url`: живая ссылка через три года умрёт вместе
         * с площадкой, снимок останется.
         *
         * На порядок в ленте «свежее» блок не влияет: статья появляется наверху
         * как всякая новая, но с пометкой возраста. Иначе постоянный читатель
         * не узнал бы, что на сайте что-то добавилось. Внутри серии, наоборот,
         * порядок исторический — по `origin.date`.
         */
        origin: z
          .object({
            /** Когда текст вышел впервые. По ней считается порядок в серии. */
            date: z.coerce.date(),

            /**
             * Что сделано с текстом при переносе. Различать обязательно:
             * между вычитанными опечатками и переписанным заново — пропасть,
             * и читателю важно знать, чей голос он слышит.
             */
            state: z
              .enum(['original', 'edited', 'rewritten'])
              .default('original'),

            /** Имя площадки для подписи. Если не задано — выводится из адреса. */
            source: z.string().optional(),

            /** Ссылка на первую публикацию. Может умереть вместе с площадкой. */
            url: z.string().url().optional(),

            /** Датированный снимок в веб-архиве. Он и есть доказательство. */
            archive: z.string().url().optional(),
          })
          .optional(),

        draft: z.boolean().default(false),
        tags: z.array(z.string()).default([]),
      })
      .refine((d) => new Set(d.series).size === d.series.length, {
        message: 'Одна и та же серия указана дважды.',
        path: ['series'],
      })
      .refine((d) => !d.lead_image || !!d.lead_alt, {
        message:
          'У ведущего кадра обязательно текстовое описание lead_alt: ' +
          'без него фотографию не «увидит» тот, кто слушает страницу.',
        path: ['lead_alt'],
      }),
});

/* ---------------------------------------------------------------------------
   Сериалы
   ------------------------------------------------------------------------ */

const series = defineCollection({
  loader: glob({ base: './src/content/series', pattern: '**/*.md' }),
  schema: ({ image }) =>
    z.object({
      id: slugField,
      title: typographic(1),
      description: typographic(1),
      icon: z.string().min(1),
      cover_image: image().optional(),
      cover_alt: typographic().optional(),

      /*
       * Подпись под обложкой серии — отдельно от `cover_alt`.
       *
       * Альтернативное описание отвечает на вопрос «что изображено» и
       * читается вслух вместо кадра. Подпись отвечает на другой вопрос —
       * «что автор хотел этим сказать», и видна всем. Шутка в описании
       * оставляет незрячего читателя без картинки, описание вместо
       * подписи — всех остальных без шутки.
       *
       * Показывается только в шапке серии: на витрине карточка и так
       * подписана названием и числом глав.
       */
      cover_caption: typographic().optional(),

      // Куда смотреть при обрезке обложки.
      //
      // Обложка показывается в двух разных пропорциях: карточкой 4:3 на
      // витрине и широкой полосой 21:9 в шапке серии. Почти любой кадр,
      // снятый не под полосу, теряет в ней верх — у портретного снимка
      // срезается макушка. Поле сдвигает точку кадрирования.
      //
      // Значение — как в CSS object-position: «center», «top»,
      // «center 25%», «left bottom».
      cover_position: z.string().default('center'),
      order: z.number().int().nonnegative(),
      draft: z.boolean().default(false),

      // Сериал или подборка.
      //
      //   serial     — сквозной сюжет: «Глава N из M», бесшовный поток чтения
      //   collection — тематический зонтик: каталог без номеров глав
      //
      // Поле заведено заранее и по умолчанию не меняет поведения. Вопрос,
      // чем считать «Ироничную пасеку», пока открыт — но благодаря этому
      // полю решение не потребует править ни одной статьи, только файл серии.
      /*
       * Кому этот журнал и чего в нём нет.
       *
       * Описание отвечает на «о чём», а спрашивают другое: «подойдёт ли мне».
       * Ответ на это и есть мостик между художественным текстом и запросом
       * человека — или модели, которой нужно кого-то сюда направить.
       *
       * Вторая половина фразы важнее первой: сказать, чего здесь нет,
       * полезнее, чем расхваливать. Тот, кто пришёл за инструкцией, уйдёт
       * сразу и не будет разочарован потом.
       */
      audience: typographic().optional(),

      kind: z.enum(['serial', 'collection']).default('serial'),

      /*
       * Каким порядком показывать список статей на странице набора.
       *
       *   story — от ранней к поздней, по дате первой публикации
       *   fresh — от свежей к ранней
       *
       * Умолчание зависит от `kind` и задаётся не здесь, а в `listOrder`
       * (`src/lib/content.ts`): у сериала порядок сюжетный, у подборки —
       * от свежего, потому что связи между текстами нет и новое важнее.
       *
       * Поле появилось ради «Разгона» (решение 28.09). Это подборка:
       * тексты 2014–2017 годов разноплановые, сквозного сюжета нет, каждый
       * самодостаточен. Но главный её признак — именно хронология: первая
       * запись берёт девизом чужое «Never stop exploring», манифест
       * 2026 года говорит ровно обратное, и весь смысл в расстоянии между
       * ними. От свежего к раннему эта дуга читается задом наперёд.
       *
       * Заводить ради порядка сортировки сериал было бы неправдой: сериал
       * обещает читателю сквозной сюжет и нумерует статьи.
       */
      order_by: z.enum(['story', 'fresh']).optional(),
    }),
});

/* ---------------------------------------------------------------------------
   Статические страницы: манифест, о нас, будущая библиотека
   ------------------------------------------------------------------------ */

const pages = defineCollection({
  loader: glob({ base: './src/content/pages', pattern: '**/*.md' }),
  schema: ({ image }) =>
    z.object({
    title: typographic(1),
    description: typographic(1),

    /*
     * Ведущий кадр — как у главы. «Манифест» и «О нас» читаются подряд
     * с обычными текстами, и страница без кадра среди них выглядит
     * служебной, хотя это тоже авторский текст.
     *
     * Поле необязательное: у справочных страниц вроде 404 кадра нет
     * и быть не должно.
     */
    lead_image: image().optional(),
    lead_alt: typographic().optional(),
    lead_caption: typographic().optional(),
    /** Чей кадр. Смысл и значения — там же, где у статей. */
    lead_credit: z.string().optional(),
    // Канонический адрес. Astro маршрутизирует по файлам, поэтому адрес
    // из метаданных разбирает один общий маршрут (ТЗ 4.3.4).
    permalink: z
      .string()
      .regex(/^\/[a-z0-9\-/]*$/, 'Адрес начинается с косой черты и пишется латиницей: "/about".'),

    /*
     * Словарь понятий — короткой формой, для машин.
     *
     * На странице определения развёрнуты: с оговорками, примерами и тем,
     * какие слова наши, а какие чужие. Машине нужна выжимка — одно
     * предложение на понятие, которое можно процитировать целиком.
     * Дублирование намеренное: короткая форма пишется отдельно, а не
     * выдирается из текста регулярным выражением, которое сломается
     * на первой же правке абзаца.
     */
    terms: z
      .array(z.object({ name: z.string().min(1), description: z.string().min(1) }))
      .optional(),
    draft: z.boolean().default(false),
    updated: z.coerce.date().optional(),
    })
    .refine((d) => !d.lead_image || !!d.lead_alt, {
      message: 'У ведущего кадра страницы обязательно текстовое описание lead_alt.',
      path: ['lead_alt'],
    }),
});

/* ---------------------------------------------------------------------------
   Настройки сайта. Три отдельных файла — три отдельные коллекции,
   потому что схемы у них разные, а Astro допускает одну схему на коллекцию.
   ------------------------------------------------------------------------ */

const menu = defineCollection({
  loader: glob({ base: './src/content/settings', pattern: 'menu.md' }),
  schema: z.object({
    items: z
      .array(
        z.object({
          title: z.string().min(1), // отображается как есть, включая индекс «00: »
          url: z.string().startsWith('/'),
        }),
      )
      .min(1),
  }),
});

const footer = defineCollection({
  loader: glob({ base: './src/content/settings', pattern: 'footer.md' }),
  schema: ({ image }) =>
    z.object({
      slogan: typographic(1),
      copyright: z.string().min(1),

      /*
       * Лицензия на фотографии — ссылкой на её текст.
       *
       * Живёт в настройках, а не в коде, по одной причине: это решение,
       * а не техническая деталь. Поменять условия — значит поменять строку
       * здесь, и разметка на всех ста девятнадцати страницах пересоберётся
       * сама. Пустое поле означает «условий не объявлено»: разметка тогда
       * молчит, а не выдумывает разрешение, которого никто не давал.
       */
      photo_license: z.string().url().optional(),
      // Цоколь: два подготовленных кадра под светлую и тёмную тему.
      // Монохром зашит в сами файлы, а не наводится фильтром (ТЗ 4.5.2).
      bookend_light: image().optional(),
      bookend_dark: image().optional(),
      social_links: z
        .array(z.object({ title: z.string().min(1), url: z.string().url() }))
        .default([]),
      ai_endpoints: z
        .array(z.object({ title: z.string().min(1), url: z.string().startsWith('/') }))
        .default([]),
    }),
});

const passport = defineCollection({
  loader: glob({ base: './src/content/settings', pattern: 'passport.md' }),
  schema: ({ image }) =>
    z.object({
      title: z.string().default('Когнитивный паспорт'),

      // Главный кадр витрины — тот самый Texture Check: макросъёмка мёда,
      // вощины, фактуры старого дерева. Поле необязательное: пока кадра нет,
      // витрина обходится типографикой, а не заглушкой.
      hero_image: image().optional(),
      hero_alt: z.string().optional(),
      hero_caption: z.string().optional(),
    })
    .refine((d) => !d.hero_image || !!d.hero_alt, {
      message: 'У главного кадра обязательно текстовое описание hero_alt.',
      path: ['hero_alt'],
    }),
});

export const collections = { posts, series, pages, menu, footer, passport };
