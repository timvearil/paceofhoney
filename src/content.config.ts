/**
 * Описание коллекций контента.
 *
 * Здесь задано, из каких полей состоит глава, серия, статическая страница и
 * файлы настроек. Astro проверяет каждый файл по этой схеме на сборке и
 * **роняет сборку** при несоответствии: опечатка в `series_id`, забытая
 * `description`, кириллица в `slug`.
 *
 * Это не бюрократия, а страховка конвейера. Ошибка ловится за двадцать секунд
 * в GitHub Actions, а не обнаруживается через неделю битой карточкой на сайте.
 *
 * Спецификация: 01_Spec/tz-paceofhoney-v2.md, разделы 1.3, 4.1, 4.4
 */

import { defineCollection, z } from 'astro:content';
import { glob } from 'astro/loaders';

/** Латинский слаг: строчные буквы, цифры, дефис-разделитель. */
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

const slugField = z
  .string()
  .regex(
    SLUG,
    'Слаг пишется латиницей в нижнем регистре, слова через дефис: "nektar-8". ' +
      'Кириллица в адресе превращается в нечитаемую мешанину процентов ' +
      'и ломается при вставке в мессенджеры.',
  );

/* ---------------------------------------------------------------------------
   Главы сериалов и одиночные материалы
   ------------------------------------------------------------------------ */

const posts = defineCollection({
  loader: glob({ base: './src/content/posts', pattern: '**/*.md' }),
  schema: ({ image }) =>
    z
      .object({
        title: z.string().min(1),
        slug: slugField,
        description: z
          .string()
          .min(1, 'Без описания превью ссылки в Telegram и MAX приходит пустым.'),

        // Серии, в которые входит статья. Одна статья может принадлежать
        // нескольким сразу: глава «НектарАкций» одновременно может быть
        // главой «Ироничной пасеки».
        //
        // Порядок значим: ПЕРВАЯ серия — ведущая. Она попадает в плашку
        // «Глава N из M» и задаёт бесшовный поток чтения. Остальные выводятся
        // ссылками под текстом.
        //
        // Номера глав здесь НЕТ намеренно. Он вычисляется на сборке — по дате,
        // отдельно внутри каждой серии. С шестью сериями и перекрёстным
        // членством ручная нумерация превратилась бы в мучение: вставил одну
        // старую статью — перенумеровывай десятки файлов в трёх сериях.
        //
        // Пустой список — одиночный материал, рендерится классическим
        // шаблоном (ТЗ 3.3.2).
        series: z.array(z.string()).default([]),

        lead_image: image().optional(),
        lead_caption: z.string().optional(),
        lead_alt: z.string().optional(),

        // Дата публикации на сайте. По ней статья встаёт в ленту «свежее».
        date: z.coerce.date(),
        updated: z.coerce.date().optional(),

        // Уточнение порядка, когда две статьи одной серии стоят на одну дату.
        // Нужно редко: обычно дата публикации и есть сюжетный порядок.
        // Но при переносе сразу многих готовых текстов даты легко совпадают,
        // и тогда порядок глав решался бы алфавитом слага — то есть случайно.
        // Сборка такой случай не пропускает: требует расставить order явно.
        order: z.number().int().optional(),

        // Дата, когда текст был написан изначально. Нужна переизданиям:
        // в «Третьей корзине желаний» статьи десятилетней давности, и внутри
        // серии они должны идти в своей исторической последовательности,
        // а не в порядке переноса на сайт. Если поле задано, порядок глав
        // считается по нему; в ленте «свежее» статья всё равно остаётся новой.
        original_date: z.coerce.date().optional(),

        draft: z.boolean().default(false),
        tags: z.array(z.string()).default([]),
      })
      .refine((d) => new Set(d.series).size === d.series.length, {
        message: 'Одна и та же серия указана дважды.',
        path: ['series'],
      })
      .refine((d) => !d.lead_image || !!d.lead_alt, {
        message:
          'У ведущего кадра обязательно текстовое описание lead_alt: ' +
          'без него фотографию не «увидит» тот, кто слушает страницу.',
        path: ['lead_alt'],
      }),
});

/* ---------------------------------------------------------------------------
   Сериалы
   ------------------------------------------------------------------------ */

const series = defineCollection({
  loader: glob({ base: './src/content/series', pattern: '**/*.md' }),
  schema: ({ image }) =>
    z.object({
      id: slugField,
      title: z.string().min(1),
      description: z.string().min(1),
      icon: z.string().min(1),
      cover_image: image().optional(),
      cover_alt: z.string().optional(),

      // Куда смотреть при обрезке обложки.
      //
      // Обложка показывается в двух разных пропорциях: карточкой 4:3 на
      // витрине и широкой полосой 21:9 в шапке серии. Почти любой кадр,
      // снятый не под полосу, теряет в ней верх — у портретного снимка
      // срезается макушка. Поле сдвигает точку кадрирования.
      //
      // Значение — как в CSS object-position: «center», «top»,
      // «center 25%», «left bottom».
      cover_position: z.string().default('center'),
      order: z.number().int().nonnegative(),
      draft: z.boolean().default(false),

      // Сериал или подборка.
      //
      //   serial     — сквозной сюжет: «Глава N из M», бесшовный поток чтения
      //   collection — тематический зонтик: каталог без номеров глав
      //
      // Поле заведено заранее и по умолчанию не меняет поведения. Вопрос,
      // чем считать «Ироничную пасеку», пока открыт — но благодаря этому
      // полю решение не потребует править ни одной статьи, только файл серии.
      kind: z.enum(['serial', 'collection']).default('serial'),
    }),
});

/* ---------------------------------------------------------------------------
   Статические страницы: манифест, о нас, будущая библиотека
   ------------------------------------------------------------------------ */

const pages = defineCollection({
  loader: glob({ base: './src/content/pages', pattern: '**/*.md' }),
  schema: z.object({
    title: z.string().min(1),
    description: z.string().min(1),
    // Канонический адрес. Astro маршрутизирует по файлам, поэтому адрес
    // из метаданных разбирает один общий маршрут (ТЗ 4.3.4).
    permalink: z
      .string()
      .regex(/^\/[a-z0-9\-/]*$/, 'Адрес начинается с косой черты и пишется латиницей: "/about".'),
    draft: z.boolean().default(false),
    updated: z.coerce.date().optional(),
  }),
});

/* ---------------------------------------------------------------------------
   Настройки сайта. Три отдельных файла — три отдельные коллекции,
   потому что схемы у них разные, а Astro допускает одну схему на коллекцию.
   ------------------------------------------------------------------------ */

const menu = defineCollection({
  loader: glob({ base: './src/content/settings', pattern: 'menu.md' }),
  schema: z.object({
    items: z
      .array(
        z.object({
          title: z.string().min(1), // отображается как есть, включая индекс «00: »
          url: z.string().startsWith('/'),
        }),
      )
      .min(1),
  }),
});

const footer = defineCollection({
  loader: glob({ base: './src/content/settings', pattern: 'footer.md' }),
  schema: ({ image }) =>
    z.object({
      slogan: z.string().min(1),
      copyright: z.string().min(1),
      // Цоколь: два подготовленных кадра под светлую и тёмную тему.
      // Монохром зашит в сами файлы, а не наводится фильтром (ТЗ 4.5.2).
      bookend_light: image().optional(),
      bookend_dark: image().optional(),
      social_links: z
        .array(z.object({ title: z.string().min(1), url: z.string().url() }))
        .default([]),
      ai_endpoints: z
        .array(z.object({ title: z.string().min(1), url: z.string().startsWith('/') }))
        .default([]),
    }),
});

const passport = defineCollection({
  loader: glob({ base: './src/content/settings', pattern: 'passport.md' }),
  schema: ({ image }) =>
    z.object({
      title: z.string().default('Когнитивный паспорт'),

      // Главный кадр витрины — тот самый Texture Check: макросъёмка мёда,
      // вощины, фактуры старого дерева. Поле необязательное: пока кадра нет,
      // витрина обходится типографикой, а не заглушкой.
      hero_image: image().optional(),
      hero_alt: z.string().optional(),
      hero_caption: z.string().optional(),
    })
    .refine((d) => !d.hero_image || !!d.hero_alt, {
      message: 'У главного кадра обязательно текстовое описание hero_alt.',
      path: ['hero_alt'],
    }),
});

export const collections = { posts, series, pages, menu, footer, passport };
