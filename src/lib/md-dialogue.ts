/**
 * Реплики в машинных текстах (`.md`-двойники, `llms-full`).
 *
 * На странице реплики из дефисов разворачивает `remark-dialogue`: пункт
 * маркированного списка становится абзацем с тире, а строка, прилипшая
 * к реплике без пустой строки, выходит наружу отдельным абзацем. Машинные
 * тексты собираются из сырого тела и этот плагин не проходят — реплики
 * уходили в них дефисом (P16-06, 29.10). Для Markdown-читалки `- …` — пункт
 * списка: диалог превращался в перечень, а авторский текст под репликой —
 * в продолжение слов персонажа.
 *
 * Здесь то же правило, только над строками:
 *
 *   - Что ты делаешь?        →  — Что ты делаешь?
 *   Тимур не ответил.            (пустая строка)
 *                                Тимур не ответил.
 *
 * Реплика и всё, что прилипло к ней, — отдельными абзацами, как на странице.
 * Без пустых строк «— » списком уже не считается, и соседние реплики
 * слиплись бы в один абзац. Нумерованные списки не трогаем — как и страница.
 * Дефис внутри реплики («- сказал Тимур. - Слайды») остаётся `typography()`.
 */

/** `- ` в начале строки; `- - ` — лишний дефис, страница его тоже прощает. */
const REPLICA = /^(?:-[ \t]+)+(?=\S)/;

export function mdDialogue(body: string): string {
  const out: string[] = [];
  // Пустая строка перед абзацем, если её ещё нет.
  const gap = () => {
    if (out.length && out[out.length - 1].trim() !== '') out.push('');
  };
  // Внутри пункта списка: строки без пустой между ними Markdown клеит к реплике.
  let inReplica = false;

  for (const line of body.split('\n')) {
    if (REPLICA.test(line)) {
      gap();
      out.push(`— ${line.replace(REPLICA, '')}`);
      inReplica = true;
    } else if (line.trim() === '') {
      out.push(line);
      inReplica = false;
    } else if (inReplica) {
      gap();
      out.push(line);
    } else {
      out.push(line);
    }
  }
  return out.join('\n');
}
