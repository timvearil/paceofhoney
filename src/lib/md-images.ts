/**
 * Кадры в машинных текстах (`.md`-двойники, `llms-full`).
 *
 * В исходниках статей кадр записан по-обсидиановски: `![[кадр.jpg|подпись]]`.
 * Для агента это не ссылка — открыть картинку по ней нельзя (аудит 17.10).
 * Здесь вставка становится обычной разметкой `![подпись](/_img/кадр.jpg)`.
 *
 * `/_img/…` — метка, а не адрес. После сборки интеграция `md-image-links`
 * заменяет её адресом файла, который страница уже отдаёт читателю (WebP
 * до 1280 px из её же `srcset`). Сделано так намеренно: `getImage` здесь
 * создавал бы свои копии и выкладывал исходники — 18.10 это дало 203 лишних
 * файла и 45 МБ, на которые никто не ссылался.
 */

import imageMap from '../content/_attachments-map.json';

/** Метка кадра по имени файла в проекте. */
export const imageMark = (file: string) => `/_img/${file}`;

/** `![[кадр.jpg|подпись]]` → `![подпись](/_img/кадр.jpg)`. */
export function mdImages(body: string): string {
  return body.replace(/!\[\[([^\]|#]+)(?:\|([^\]]*))?\]\]/g, (_, raw: string, cap?: string) => {
    const name = (imageMap as Record<string, string>)[raw.trim()] ?? raw.trim();
    return `![${(cap ?? '').trim()}](${imageMark(name)})`;
  });
}
