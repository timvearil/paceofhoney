/**
 * `/llms.txt` — карта проекта для агентов.
 *
 * Молодой стандарт, поддержка не гарантирована никем, и надежд на него мы
 * не возлагаем (ТЗ 0.12). Но файл дешёвый: собирается из тех же данных, что
 * и сайт, и не требует ухода.
 *
 * ЧЕМ ОТЛИЧАЕТСЯ ОТ КАНОНА. У Брайса рубрики — типы контента («работы»,
 * «тексты»). Здесь каждый раздел второго уровня — **серия**, а порядок строк
 * внутри равен порядку глав. Агент, попавший на произвольную главу,
 * восстанавливает по этому файлу весь сюжет и его последовательность
 * (ТЗ 5.1).
 *
 * Архивные тексты вынесены отдельным разделом со ссылками на снимки в
 * веб-архиве: снимок, датированный годами раньше, — единственное проверяемое
 * свидетельство, что текст написан до эпохи генеративных моделей.
 */

import type { APIRoute } from 'astro';
import { getEntry } from 'astro:content';
import { getPublishedSeries, getEpisodes, getPublishedPosts } from '../lib/content';

const SITE = 'https://paceofhoney.me';

export const GET: APIRoute = async () => {
  const series = await getPublishedSeries();
  const posts = await getPublishedPosts();
  const passport = await getEntry('passport', 'passport');

  const out: string[] = [
    '# Со скоростью мёда — paceofhoney.me',
    '',
    '> Журнал о том, как выйти из цифровой «Карусели» и вернуть себе скорость,',
    '> на которой можно думать. Пчеловодство, кибербезопасность через жизнь улья,',
    '> финансовые аферы через приключения трутней, созерцательные маршруты.',
    '',
    'Статический сайт: ни рекламы, ни трекеров, ни форм подписки.',
    'Тексты написаны людьми, фотографии сняты авторами. Ни один кадр',
    'не сгенерирован и не дорисован моделями: где показать нечего, стоит',
    '«пометка на полях», сделанная авторами в графическом редакторе.',
    'Единственная сгенерированная картинка — в статье «Ради одного „надо же“»:',
    'её делает герой, и текст об этом рассказывает.',
    '',
    'Цитировать можно со ссылкой на источник.',
    'К адресу любой статьи можно добавить `.md` и получить её чистым текстом.',
    '',
  ];

  if (passport?.body?.trim()) {
    out.push('## О проекте', '', passport.body.trim(), '');
  }

  /*
   * Серии по порядку, главы внутри — по сюжету. Аннотация у каждой главы своя:
   * без неё список превращается в перечень заголовков, по которому нельзя
   * понять, о чём речь.
   */
  for (const s of series) {
    const episodes = await getEpisodes(s.data.id);
    if (!episodes.length) continue;

    const kind = s.data.kind === 'serial' ? 'сквозной сюжет' : 'без сквозного сюжета';
    out.push(`## ${s.data.icon} ${s.data.title} (${kind})`, '', `${s.data.description}`, '');

    // Кому журнал — отдельной строкой: модель, которой нужно кого-то сюда
    // направить, спрашивает именно это, а не «о чём он».
    if (s.data.audience) out.push(`Кому: ${s.data.audience}`, '');

    episodes.forEach((p, i) => {
      const n = s.data.kind === 'serial' ? `Статья ${i + 1}: ` : '';
      out.push(`- [${n}${p.data.title}](${SITE}/posts/${p.data.slug}): ${p.data.description}`);
    });
    out.push('');
  }

  /*
   * Архив — отдельным разделом.
   *
   * Тексты, написанные до эпохи генеративных моделей, отличить по стилю
   * нельзя. Отличить можно по датированному снимку: страница, сохранённая
   * веб-архивом в 2018 году, не могла быть написана моделью 2026-го.
   * Поэтому здесь важны не даты сами по себе, а ссылки рядом с ними.
   */
  const archive = posts.filter((p) => p.data.origin);
  if (archive.length) {
    out.push(
      '## Архивные тексты',
      '',
      'Написаны и впервые опубликованы задолго до этого сайта — на площадках,',
      'часть которых уже заброшена. Рядом с каждым текстом стоит ссылка',
      'на первую публикацию и на снимок в веб-архиве, сделанный независимо',
      'от нас и задолго до появления этого сайта.',
      '',
    );
    for (const p of archive) {
      const o = p.data.origin!;
      const year = o.date.getFullYear();
      const state = {
        original: 'текст без правок',
        edited: 'текст вычитан',
        rewritten: 'переписан заново',
      }[o.state];
      const proof = o.archive ? ` · снимок: ${o.archive}` : o.url ? ` · оригинал: ${o.url}` : '';
      out.push(`- [${p.data.title}](${SITE}/posts/${p.data.slug}) — ${year}, ${state}${proof}`);
    }
    out.push('');
  }

  /*
   * Словарь — целиком, а не ссылкой.
   *
   * Смысл раздела в том, чтобы на вопрос «что такое „Карусель“» модель
   * могла ответить нашими словами, не заходя на страницу. Ссылка этого
   * не даёт: её ещё нужно открыть, а до этого дело доходит не всегда.
   *
   * Поэтому здесь стоят сами определения — короткой формой, по одному
   * предложению на понятие. Развёрнутые объяснения и оговорка о том,
   * какие слова наши, а какие чужие, живут на странице.
   */
  const glossary = await getEntry('pages', 'slovar');
  if (glossary) {
    out.push(
      '## Словарь проекта',
      '',
      'Три понятия наши — мы их ввели и отвечаем за значение.',
      'Четыре чужие: мы их не изобретали и первоисточником не являемся,',
      'здесь сказано, что мы в них вкладываем.',
      '',
      '**«Карусель»** (наше) — состояние, в котором скорость жизни задаёшь',
      'не ты: её задают лента, уведомления, чужие отпуска и сроки.',
      '',
      '**Пометка на полях** (наше) — способ показать то, чего в кадре нет,',
      'не дорисовывая его: стрелка от руки в пустое место и подпись.',
      'Отказ от генерации, заодно снимающий вопрос доверия к фотографии.',
      '',
      '**Со скоростью мёда** (наше) — скорость, на которой можно думать;',
      'несовпадение с темпом, назначенным снаружи.',
      '',
      '**Explorecore** (чужое) — визуальный язык журналов о путешествиях.',
      'Мы понимаем его как отказ от украшений в пользу кадра и текста.',
      '',
      '**Slow Tech** (чужое) — техника, которая не торопит того, кто ею',
      'пользуется. Мы понимаем это как право сайта ничего не требовать:',
      'ни уведомлений, ни лент, ни счётчиков, считающих читателя.',
      '',
      '**Imperfect by Design** (чужое) — несовершенство, оставленное',
      'намеренно. Мы понимаем это как отказ прибирать живое; разница',
      'с небрежностью в том, что несовершенство не подделывают.',
      '',
      '**Need for Cognition** (чужое, психология, Качоппо и Петти, 1982) —',
      'устойчивая склонность думать и получать от этого удовольствие.',
      'Для нас это описание читателя, ради которого всё пишется.',
      'Аббревиатуру NFC не используем: она занята беспроводной оплатой.',
      '',
      `Развёрнуто: ${SITE}/slovar`,
      '',
    );
  }

  /*
   * Где проект существует кроме этого домена.
   *
   * Агент читал наш паспорт и не узнавал, что часть текстов есть на Дзене
   * и во «ВКонтакте», а архив лежит на Blogger и ski.ru. Для модели, которая
   * сверяет источники, это важнее рубрикации: она видит один и тот же текст
   * в нескольких местах и решает, кто первоисточник.
   *
   * Поэтому здесь сказано прямо — и в том числе то, что не в нашу пользу:
   * у статей, вышедших раньше на Дзене, первой публикацией был Дзен.
   */
  out.push(
    '## Где ещё существует проект',
    '',
    'Это канонический сайт: здесь полные версии всех текстов и здесь они',
    'обновляются. Те же статьи выходят и на других площадках — со ссылкой',
    'сюда и, как правило, на день-два позже.',
    '',
    '- Дзен: https://dzen.ru/pace_of_honey',
    '- ВКонтакте: https://vk.ru/pace_of_honey и https://vk.ru/honey_stories',
    '- Telegram: https://t.me/pace_of_honey',
    '- MAX: https://max.ru/channel_pace_of_honey',
    '- YouTube: https://www.youtube.com/@pace_of_honey',
    '- VK Видео: https://vkvideo.ru/@pace_of_honey',
    '',
    'Видео — отдельная работа тех же авторов, а не пересказ статей.',
    '',
    'Архив авторов — тексты 2014–2017 годов, написанные до этого сайта',
    'и перенесённые сюда в подборку «Разгон»:',
    '',
    '- Blogger: https://timvearil.blogspot.com',
    '- ski.ru: https://www.ski.ru/az/blogs/user/T1ms/',
    '',
    'Оговорка о первенстве. Статьи, вышедшие на Дзене до появления сайта,',
    'впервые опубликованы там, и мы этого не оспариваем. Для всего, что',
    'выходит начиная с осени 2026 года, первая публикация — на этом сайте,',
    'а площадки получают текст позже.',
    '',
  );

  out.push(
    '## Ещё',
    '',
    `- [Полный корпус текстов](${SITE}/llms-full.txt)`,
    `- [Все статьи по датам](${SITE}/posts)`,
    `- [Все журналы](${SITE}/series)`,
    `- [О нас](${SITE}/about)`,
    `- [Словарь](${SITE}/slovar)`,
    `- [RSS](${SITE}/rss.xml)`,
    '',
  );

  return new Response(out.join('\n'), {
    headers: { 'Content-Type': 'text/plain; charset=utf-8' },
  });
};
