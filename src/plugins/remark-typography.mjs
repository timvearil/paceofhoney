/**
 * Типографика: то, что автор не обязан набирать руками.
 *
 * ЗАЧЕМ. На клавиатуре нет ни длинного тире, ни ёлочек. Набирать их через
 * коды — значит думать о раскладке вместо текста, а потом всё равно забыть
 * в половине мест. Проверка по семнадцати статьям показала ровно это:
 * дефис вместо тире в каждой, прямые кавычки в шестнадцати.
 *
 * ЧТО ДЕЛАЕМ.
 *
 *   слово - слово   →  слово — слово      (дефис между пробелами — это тире)
 *   "фраза"         →  «фраза»            (прямые кавычки — в ёлочки)
 *   ...             →  …                   (три точки — одним знаком)
 *
 * ЧЕГО НЕ ТРОГАЕМ. Плагин ходит только по обычному тексту. Содержимое
 * `кода`, ссылок и адресов лежит в других узлах разметки и остаётся как
 * есть — иначе первый же путь вида `a - b` в примере кода превратился бы
 * в тире, а кавычки в названии файла — в ёлочки.
 *
 * Дефис внутри слова (что-то, из-за) не задет: правило требует пробелов
 * с обеих сторон. Это и есть надёжный признак тире в русском тексте.
 *
 * ПОРЯДОК. Плагин идёт после `remark-dialogue`: тот уже развернул реплики
 * в абзацы и поставил тире в начале строки. Здесь — остальной текст.
 */

import { visit } from 'unist-util-visit';

/**
 * Кавычки по соседству, а не по счёту.
 *
 * Раньше здесь был счётчик: первая кавычка — открывающая, вторая —
 * закрывающая, и так по кругу. Он разваливался на разметке. Абзац
 * «"**Как собрать больше нектара**"» приходит сюда двумя кусками — до
 * жирного и после, — счётчик в каждом начинается с нуля, и обе кавычки
 * выходят открывающими. На сайте таких мест нашлось одиннадцать.
 *
 * Правило Тимура точнее: открывающая ставится, только если слева ничего
 * нет или стоит пробел, скобка либо тире. Во всех прочих случаях — после
 * буквы, цифры, точки, запятой — кавычка закрывающая. Это не зависит
 * ни от разметки, ни от того, сколько кавычек было раньше.
 *
 * `prev` — последний символ перед этим куском текста. Плагин передаёт его,
 * проходя абзац по порядку; при вызове из схемы контента строка целая,
 * и он не нужен.
 */
const OPENS_AFTER = /[\s(\[{«„—–-]/;

/*
 * Кавычка внутри кавычки — лапками, а не второй парой ёлочек.
 *
 * «Ради одного „надо же“» — так набирают в русской книге. Два одинаковых
 * знака подряд, «Ради одного «надо же»», читаются как сбой вёрстки:
 * непонятно, где кончилась внешняя цитата.
 *
 * Поэтому решений два, и они независимы. Сосед слева говорит, открывающая
 * кавычка или закрывающая. Глубина говорит, какой знак взять: снаружи
 * ёлочки, внутри лапки. Глубина живёт в пределах абзаца и не переносится
 * дальше — незакрытая кавычка не должна портить следующий.
 */
const MARKS = { open: ['«', '„'], close: ['»', '“'] };

/** Всё, что может оказаться кавычкой: прямая, лапки, ёлочки. */
const QUOTE = /["“”«»„]/;
/** Знаки, которые сами по себе уже говорят, что они открывающие. */
const OPENING = /[«„]/;
/** И закрывающие. Прямая кавычка не говорит ничего — её решает сосед. */
const CLOSING = /[»]/;

function quotes(value, ctx) {
  let out = '';

  for (const ch of value) {
    /*
     * Разбираем не только прямые кавычки, но и уже набранные ёлочки.
     * Автор ставит их руками, когда помнит, — и внутренняя цитата тогда
     * оказывается такой же, как внешняя. Приводим к общему виду: решает
     * не то, какой знак написан, а где он стоит.
     */
    if (QUOTE.test(ch)) {
      const opens = OPENING.test(ch)
        ? true
        : CLOSING.test(ch)
          ? false
          : ctx.prev === '' || OPENS_AFTER.test(ctx.prev);

      if (opens) {
        out += MARKS.open[Math.min(ctx.depth, 1)];
        ctx.depth += 1;
      } else {
        ctx.depth = Math.max(0, ctx.depth - 1);
        out += MARKS.close[Math.min(ctx.depth, 1)];
      }
    } else {
      out += ch;
    }
    ctx.prev = ch;
  }

  return out;
}

export function typography(value, state) {
  /*
   * Состояние разбора кавычек — только своё.
   *
   * Второй параметр необязателен, и функцию легко передать обработчиком
   * куда-нибудь, где вторым аргументом приходит чужое: zod шлёт в `transform`
   * свой объект для ошибок, `map` шлёт номер элемента. Тогда счётчик
   * вложенности оказывается `undefined`, выбор кавычки по нему даёт `NaN`,
   * и вместо ёлочки в текст уходит пустота. Так 01.10 по всему сайту
   * встало `Подписка undefinedЗавтраundefined`.
   *
   * Поэтому чужой объект здесь не доверяется: если в нём нет счётчика —
   * заводим свой. Вызывать правильно всё равно нужно, но одна ошибка вызова
   * больше не портит текст молча.
   */
  const ctx =
    state && typeof state.depth === 'number' && typeof state.prev === 'string'
      ? state
      : { prev: '', depth: 0 };

  let v = String(value);

  // Дефис между пробелами — тире. Неразрывный пробел перед ним не ставим:
  // строка и так не начнётся с тире, а лишние символы мешают поиску.
  v = v.replace(/ - /g, ' — ');

  // Тире в начале строки после переноса — тот же случай.
  v = v.replace(/^- /, '— ');

  v = v.replace(/\.{3}/g, '…');
  return quotes(v, ctx);
}

/*
 * Блоки, внутри которых живёт обычный текст. Абзац проходим целиком,
 * от куска к куску, передавая последний символ дальше: иначе разметка
 * внутри предложения снова разорвала бы кавычки.
 */
const TEXT_BLOCKS = new Set(['paragraph', 'heading', 'tableCell']);

export function remarkTypography() {
  return (tree) => {
    visit(tree, (block) => {
      if (!TEXT_BLOCKS.has(block.type)) return;

      // Состояние на абзац: сосед слева и глубина вложенности.
      const ctx = { prev: '', depth: 0 };
      visit(block, 'text', (node) => {
        node.value = typography(node.value, ctx);
      });
    });
  };
}
